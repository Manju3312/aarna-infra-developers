import { ProjectItem, PlotUnit } from '@/types';

// Helper to generate realistic plot layouts
function generatePlotUnits(
  count: number,
  baseRate: number,
  sizeOptions: number[] = [150, 183, 200, 267, 300, 400]
): PlotUnit[] {
  const facings: PlotUnit['facing'][] = ['EAST', 'WEST', 'NORTH', 'CORNER'];
  
  return Array.from({ length: count }, (_, i) => {
    const num = i + 1;
    const facing = facings[num % facings.length];
    const sqYards = sizeOptions[num % sizeOptions.length];
    const rate = facing === 'CORNER' ? Math.round(baseRate * 1.1) : baseRate;
    const status = num % 7 === 0 ? 'SOLD' : num % 5 === 0 ? 'RESERVED' : 'AVAILABLE';

    return {
      number: num,
      facing,
      sqYards,
      ratePerYard: rate,
      status,
      dimensions: `${Math.round(Math.sqrt(sqYards * 9) * 0.8)}' x ${Math.round(Math.sqrt(sqYards * 9) * 1.25)}'`,
      roadWidthFt: facing === 'CORNER' ? 60 : 40,
    };
  });
}

